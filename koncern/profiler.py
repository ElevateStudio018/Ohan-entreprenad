def _profil(bas, **over):
    p = {k: (dict(v) if isinstance(v, dict) else list(v) if isinstance(v, list) else v) for k, v in bas.items()}
    for k, v in over.items():
        if k in ("t", "bild"):
            p[k] = {**p.get(k, {}), **v}
        else:
            p[k] = v
    return p


